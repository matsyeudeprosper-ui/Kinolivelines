import hashlib, io, json, os, re, threading, time

HERE = os.path.dirname(os.path.abspath(__file__))
PINS = os.path.join(HERE, "kino_pins.json")
_LOCK = threading.Lock()
_NUM = re.compile(r"([+\-−]?\d+(?:[.,]\d+)?)\s?(\$|%|R\b|trades?|tirages?|draws?|jours?|days?|min(?:utes)?|h\b)", re.I)


def _load():
    try:
        return json.load(open(PINS, encoding="utf-8"))
    except Exception:
        return {}


def _mut(fn):
    with _LOCK:
        d = _load()
        fn(d)
        tmp = PINS + ".%d.tmp" % threading.get_ident()
        io.open(tmp, "w", encoding="utf-8").write(json.dumps(d, ensure_ascii=False, indent=1))
        for _ in range(20):
            try:
                os.replace(tmp, PINS)
                return
            except PermissionError:
                time.sleep(0.05)


def _where(r, lang):
    w = r.get("where") or "none"
    since = r.get("since") or ""
    if w == "real":
        return ("SUR LEUR COMPTE RÉEL%s" % ((" depuis %s" % since) if since else "")) if lang != "en" else ("ON THEIR REAL ACCOUNT%s" % ((" since %s" % since) if since else ""))
    if w == "ghost":
        _gn, _gv = r.get("ghost_n"), r.get("ghost_net")
        _gx = (("" if _gn is None else (" - en fantôme : %d trade(s) pour l'instant%s" % (_gn, (", %+.2f $ fictifs" % _gv) if _gn else ""))) if lang != "en"
               else ("" if _gn is None else (" - in ghost: %d trade(s) so far%s" % (_gn, (", %+.2f $ pretend" % _gv) if _gn else ""))))
        return ("EN FANTÔME (argent fictif)%s%s" % ((" depuis %s" % since) if since else "", _gx)) if lang != "en" else ("IN GHOST MODE (pretend money)%s%s" % ((" since %s" % since) if since else "", _gx))
    return "NULLE PART (ne tourne pas : ni compte, ni fantôme)" if lang != "en" else "NOWHERE (not running: no account, no ghost)"


def _test(t, lang):
    if not t:
        return "pas de test" if lang != "en" else "no test"
    if t.get("queued"):
        return ("test EN FILE depuis %s UTC (quelques minutes une fois son tour venu)" % t["queued"]) if lang != "en" else ("test QUEUED since %s UTC (a few minutes once its turn comes)" % t["queued"])
    # 2026-10-25 18:35 (watch): "Owl de nuit ... 28 trades en fictif, +13,35 $" - the TEST figures read as ghost results.
    # The test is a replay of PAST prices; the ghost trades from now on: the label says which is which.
    # 2026-10-25 19:43 (watch): "je ne peux pas te dire s'il compte les frais" - it always does (real spread); say so.
    s = "TEST SUR LES PRIX PASSÉS (pas le fantôme, pas le réel) : %+.2f $ sur %d trades, %d %% gagnés, pire creux %.0f $, frais du courtier compris (écart réel de chaque seconde)" % (float(t.get("net") or 0), int(t.get("trades") or 0), round(100 * float(t.get("win_rate") or 0)), float(t.get("cc_dd") or 0)) \
        if lang != "en" else "TEST ON PAST PRICES (not the ghost, not real): %+.2f $ on %d trades, %d%% won, worst dip %.0f $, broker costs included (the real spread of every second)" % (float(t.get("net") or 0), int(t.get("trades") or 0), round(100 * float(t.get("win_rate") or 0)), float(t.get("cc_dd") or 0))
    if t.get("h1") is not None and t.get("h2") is not None:
        s += ((", 1re moitié %+.2f $, 2e moitié %+.2f $" if lang != "en" else ", first half %+.2f $, second half %+.2f $")
              % (float(t["h1"]), float(t["h2"])))
    if t.get("when"):
        s += (" (testé le %s)" if lang != "en" else " (tested %s)") % t["when"]
    return s


def _luck(l, lang):
    if not l:
        return "pas de test de chance" if lang != "en" else "no luck test"
    st = l.get("state")
    if st == "queued":
        return ("test de chance EN FILE, %d devant" % int(l.get("ahead") or 0)) if lang != "en" else ("luck test QUEUED, %d ahead" % int(l.get("ahead") or 0))
    if st == "running":
        return ("test de chance EN COURS : %s/%s tirages, %s robots au hasard aussi bons (la règle en tolère %s)" % (l.get("n"), l.get("max") or 100, l.get("beats"), l.get("allow") or 5)) \
            if lang != "en" else ("luck test RUNNING: %s/%s draws, %s random robots as good (the rule allows %s)" % (l.get("n"), l.get("max") or 100, l.get("beats"), l.get("allow") or 5))
    if st == "pass":
        return ("test de chance RÉUSSI : %s robots au hasard sur %s aussi bons (tolérance %s)" % (l.get("beats"), l.get("n") or 100, l.get("allow") or 5)) \
            if lang != "en" else ("luck test PASSED: %s random robots of %s as good (allowed %s)" % (l.get("beats"), l.get("n") or 100, l.get("allow") or 5))
    if st in ("fail", "data_changed"):
        return ("test de chance RATÉ : %s robots au hasard aussi bons après %s tirages (arrêt anticipé si 3 dès les premiers)" % (l.get("beats"), l.get("n"))) \
            if lang != "en" else ("luck test FAILED: %s random robots as good after %s draws (early stop when 3 in the first ones)" % (l.get("beats"), l.get("n")))
    return str(st)


def state_block(data, lang="fr"):
    """data = {"robots": [{name, id, market, where, since, steps:{entry,stop,exit,filters}, test, luck}], "account": {robot, since, n}}"""
    L = []
    acc = data.get("account") or {}
    if acc.get("robot"):
        L.append(("Robot de LEUR COMPTE RÉEL : %s%s%s" % (acc["robot"], (" depuis %s" % acc["since"]) if acc.get("since") else "", (", %s trades" % acc["n"]) if acc.get("n") is not None else ""))
                 if lang != "en" else ("Robot on THEIR REAL ACCOUNT: %s%s%s" % (acc["robot"], (" since %s" % acc["since"]) if acc.get("since") else "", (", %s trades" % acc["n"]) if acc.get("n") is not None else "")))
    else:
        L.append("Aucun robot sur leur compte réel" if lang != "en" else "No robot on their real account")
    for r in (data.get("robots") or [])[:12]:
        st = r.get("steps") or {}
        steps = ", ".join("%s: %s" % (k, st[k]) for k in ("entry", "stop", "exit", "filters") if st.get(k))
        L.append("• %s (%s) - %s | %s | %s | %s" % (r.get("name"), r.get("market") or "BTCUSD", _where(r, lang), steps or ("étapes ?" if lang != "en" else "steps ?"),
                                                    _test(r.get("test"), lang), _luck(r.get("luck"), lang)))
    txt = "\n".join(L)
    v = hashlib.md5(txt.encode("utf-8")).hexdigest()[:6]
    head = ("ÉTAT RÉEL DE LEURS ROBOTS (v%s, construit par le code à l'instant - LA SEULE SOURCE pour 'il tourne où', la cible, le stop, "
            "le test, le test de chance ; contredire ce bloc est une erreur) :" if lang != "en" else
            "REAL STATE OF THEIR ROBOTS (v%s, built by code this minute - THE ONLY SOURCE for where a robot runs, its target, its stop, its "
            "test and luck test; contradicting this block is a mistake):") % v
    return head + "\n" + txt


