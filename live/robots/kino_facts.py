def pin(cid, text, robots):
    """the numbers said about a named robot: {robot: {unit: (value, t, sentence)}}"""
    if not text or not robots:
        return
    now = time.time()
    found = []
    for s in re.split(r"(?<=[.!?])\s+", str(text)):
        names = [n for n in robots if n and n.lower() in s.lower()]
        if not names:
            continue
        for m in _NUM.finditer(s):
            v = m.group(1).replace(",", ".").replace("−", "-")
            unit = m.group(2).lower().rstrip("s")
            if unit in ("trade", "tirage", "draw"):
                unit = "trades" if unit == "trade" else "draws"
            found.append((names[0], unit, v, s.strip()[:160]))
    if not found:
        return

    def f(d):
        u = d.setdefault(cid, {})
        for name, unit, v, s in found:
            u.setdefault(name, {})[unit] = {"v": v, "t": now, "s": s}
        for name in list(u):
            for unit in list(u[name]):
                if now - float(u[name][unit].get("t") or 0) > 3 * 86400:
                    del u[name][unit]
            if not u[name]:
                del u[name]
    _mut(f)


def pinned_block(cid, lang="fr"):
    u = _load().get(cid) or {}
    if not u:
        return ""
    L = []
    for name, units in u.items():
        L.append("%s: %s" % (name, "; ".join("%s %s (said %s)" % (x["v"], unit, time.strftime("%d/%m %H:%M", time.gmtime(float(x["t"])))) for unit, x in units.items())))
    return ("CE QUE TU AS DÉJÀ DIT COMME CHIFFRES sur chaque robot dans cette conversation (un chiffre différent pour le même robot sans nouvelle carte de résultat = incohérence à corriger) : "
            if lang != "en" else "THE FIGURES YOU ALREADY GAVE for each robot in this conversation (a different figure for the same robot without a new result card = an inconsistency to fix): ") + " | ".join(L)


